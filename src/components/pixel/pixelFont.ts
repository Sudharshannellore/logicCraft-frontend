/** 3x5 bitmap font for crisp text inside low-resolution canvases. */
const glyphs: Record<string, string[]> = {
  '0': ['111', '101', '101', '101', '111'],
  '1': ['010', '110', '010', '010', '111'],
  '2': ['111', '001', '111', '100', '111'],
  '3': ['111', '001', '111', '001', '111'],
  '4': ['101', '101', '111', '001', '001'],
  '5': ['111', '100', '111', '001', '111'],
  '6': ['111', '100', '111', '101', '111'],
  '7': ['111', '001', '010', '010', '010'],
  '8': ['111', '101', '111', '101', '111'],
  '9': ['111', '101', '111', '001', '111'],
  '+': ['000', '010', '111', '010', '000'],
  X: ['101', '101', '010', '101', '101'],
  P: ['111', '101', '111', '100', '100'],
  '{': ['011', '010', '110', '010', '011'],
  '}': ['110', '010', '011', '010', '110'],
  '<': ['001', '010', '100', '010', '001'],
  '>': ['100', '010', '001', '010', '100'],
  '/': ['001', '001', '010', '100', '100'],
  '(': ['010', '100', '100', '100', '010'],
  ')': ['010', '001', '001', '001', '010'],
  ';': ['000', '010', '000', '010', '100'],
  '=': ['000', '111', '000', '111', '000'],
  ' ': ['000', '000', '000', '000', '000'],
}

export function drawPixelText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string) {
  ctx.fillStyle = color
  let cursor = Math.round(x)
  const top = Math.round(y)
  for (const ch of text) {
    const glyph = glyphs[ch] ?? glyphs[' ']
    glyph.forEach((row, gy) => {
      for (let gx = 0; gx < 3; gx++) if (row[gx] === '1') ctx.fillRect(cursor + gx, top + gy, 1, 1)
    })
    cursor += 4
  }
}

export function pixelTextWidth(text: string) {
  return text.length * 4 - 1
}
